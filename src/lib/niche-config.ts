/** Look up config for a given niche key */
export function getNicheConfig(nicheKey: string): NicheConfig {
  return NICHES.find((n) => n.nicheKey === nicheKey) ?? NICHES[NICHES.length - 1]!;
}

/** Get all categories for a niche, returns a default list if not found */
export function getNicheCategories(nicheKey: string): string[] {
  return getNicheConfig(nicheKey).categories;
}

