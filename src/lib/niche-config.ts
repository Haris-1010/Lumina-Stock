// Niche-specific business configuration.
// Each niche defines features, categories, defaults, and business rules
// that are surfaced during onboarding Step 4 (Configure) and Step 5 (Products).

export interface NicheFeature {
  key: string;
  label: string;
  labelUr: string;
  description: string;
  descriptionUr: string;
  icon: string; // emoji
  defaultOn: boolean;
  required?: boolean; // cannot be toggled off
  businessImpact: string; // short "why this matters" text
}

export interface NicheConfig {
  nicheKey: string;
  displayName: string;
  categories: string[];
  skuPrefix: string;
  /** Default unit type for products in this niche */
  defaultUnit: "UNIT" | "KG" | "GRAM" | "LITER" | "PACK" | "STRIP" | "BOX" | "SET" | "PAIR";
  defaultReorderPoint: number;
  defaultLeadTimeDays: number;
  /** Suggested tax rate % (0 = not taxed) */
  suggestedTaxRate: number;
  /** Features to show in the niche settings step */
  features: NicheFeature[];
  /** Example hint shown in the quick-add table */
  quickAddPlaceholder: string;
  /** A key business insight about this niche */
  businessTip: string;
  businessTipUr: string;
  /** Columns to show in quick-add table (always includes name, price, stock) */
  extraColumns?: Array<"expiry" | "batch" | "brand" | "size" | "color" | "partNumber" | "warranty">;
  /** Whether this niche typically needs expiry tracking */
  trackExpiry: boolean;
}

