const messagesByLanguage: Record<AppLanguage, MessageCatalog> = {
  en: englishMessages,
  ur: urduMessages,
};

export const SUPPORTED_LANGUAGES: Array<{ code: AppLanguage; nativeLabel: string }> = [
  { code: "en", nativeLabel: "English" },
  { code: "ur", nativeLabel: "اردو" },
];

export function resolveLanguage(value: string | null | undefined): AppLanguage {
  if (value === "ur") return "ur";
  return DEFAULT_LANGUAGE;
}

export function getLanguageDirection(language: AppLanguage): "ltr" | "rtl" {
  return language === "ur" ? "rtl" : "ltr";
}

function interpolate(
  message: string,
  variables?: Record<string, string | number>
): string {
  if (!variables) return message;

  return message.replace(/\{(\w+)\}/g, (_, variableName: string) => {
    const value = variables[variableName];
    return value === undefined ? `{${variableName}}` : String(value);
  });
}

export function translate(
  language: AppLanguage,
  key: TranslationKey,
  variables?: Record<string, string | number>
): string {
  const localizedMessage =
    messagesByLanguage[language][key] || messagesByLanguage.en[key] || key;

  return interpolate(localizedMessage, variables);
}

export function createTranslator(language: AppLanguage) {
  return (key: TranslationKey, variables?: Record<string, string | number>) =>
    translate(language, key, variables);
}

type AuthErrorKey =
  | "auth.errors.requiredFields"
  | "auth.errors.passwordShort"
  | "auth.errors.accountExists"
  | "auth.errors.invalidCredentials"
  | "auth.errors.orgSuspended"
  | "auth.errors.dbConnection";

export function translateAuthError(
  errorKey: AuthErrorKey,
  language: AppLanguage
) {
  return translate(language, errorKey);
}

